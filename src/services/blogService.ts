import { getApiBaseUrl } from './apiConfig';

const LOCAL_STORAGE_KEY = 'soundabode_blog_posts';
const API_BASE_URL = getApiBaseUrl();

export class BlogService {
  public static normalizePost(post: any): BlogPost {
    if (!post) return post;
    const authorName = post.author?.name || post.authorName || 'Soundabode';
    const authorRole = post.author?.role || post.authorRole || 'Academy Editorial';
    const authorAvatarUrl = post.author?.avatarUrl || post.authorAvatarUrl || '';

    return {
      ...post,
      author: {
        name: authorName,
        role: authorRole,
        avatarUrl: authorAvatarUrl,
      },
    };
  }

  private static getStoredPosts(): BlogPost[] {
    try {
      const stored = localStorage.getItem(LOCAL_STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed)) {
          const hasLegacy = parsed.some((p: any) => ['post-1', 'post-2', 'post-3', 'post-4'].includes(p.id));
          if (!hasLegacy && parsed.length >= 6) {
            return parsed.map((p) => this.normalizePost(p));
          }
        }
      }
    } catch {
      // Fallback if localStorage is unavailable
    }
    // Automatically save official blogs into storage
    this.savePosts(OFFICIAL_BLOG_POSTS);
    return OFFICIAL_BLOG_POSTS;
  }

  private static savePosts(posts: BlogPost[]): void {
    try {
      const normalized = posts.map((p) => this.normalizePost(p));
      localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(normalized));
    } catch {
      // Fallback
    }
  }

  public static getAllPosts(): BlogPost[] {
    if (typeof window !== 'undefined') {
      fetch(`${API_BASE_URL}/posts`)
        .then((res) => (res.ok ? res.json() : null))
        .then((remotePosts) => {
          if (Array.isArray(remotePosts) && remotePosts.length > 0) {
            const hasLegacy = remotePosts.some((p: any) => ['post-1', 'post-2', 'post-3', 'post-4'].includes(p.id));
            if (!hasLegacy && remotePosts.length >= 6) {
              const normalized = remotePosts.map((p) => this.normalizePost(p));
              localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(normalized));
            }
          }
        })
        .catch(() => {});
    }
    return this.getStoredPosts();
  }

  /** Fetch the published post catalogue so readers on any device see admin posts. */
  public static async fetchRemotePosts(): Promise<BlogPost[]> {
    try {
      const response = await fetch(`${API_BASE_URL}/posts`);
      if (!response.ok) return this.getStoredPosts();
      const remotePosts = await response.json();
      if (!Array.isArray(remotePosts) || remotePosts.length === 0) return this.getStoredPosts();
      const posts = remotePosts.map((post) => this.normalizePost(post));
      this.savePosts(posts);
      return posts;
    } catch {
      return this.getStoredPosts();
    }
  }

  public static getFeaturedPosts(): BlogPost[] {
    const posts = this.getStoredPosts();
    return posts.filter((post) => post.isFeatured);
  }

  public static getLatestPosts(limit = 4): BlogPost[] {
    const posts = this.getStoredPosts();
    return posts.slice(0, limit);
  }

  public static getPostBySlug(slug: string): BlogPost | undefined {
    return this.getStoredPosts().find((post) => post.slug === slug);
  }

  public static searchPosts(query: string, category = 'ALL'): BlogPost[] {
    let posts = this.getStoredPosts();

    if (category && category !== 'ALL') {
      posts = posts.filter((post) => post.category === category);
    }

    if (query && query.trim() !== '') {
      const q = query.toLowerCase().trim();
      posts = posts.filter(
        (post) =>
          post.title.toLowerCase().includes(q) ||
          post.excerpt.toLowerCase().includes(q) ||
          (post.tags && post.tags.some((t) => t.toLowerCase().includes(q)))
      );
    }

    return posts;
  }

  public static createPost(newPost: BlogPost): BlogPost {
    const posts = this.getStoredPosts();
    posts.unshift(newPost);
    this.savePosts(posts);

    if (typeof window !== 'undefined') {
      fetch(`${API_BASE_URL}/posts`, {
        method: 'POST',
        headers: AuthService.getAuthHeaders(),
        body: JSON.stringify(newPost),
      }).catch((err) => console.warn('Atlas blog sync notice:', err));
    }

    return newPost;
  }

  public static updatePost(id: string, updatedFields: Partial<BlogPost>): BlogPost | null {
    const posts = this.getStoredPosts();
    const index = posts.findIndex((p) => p.id === id);
    if (index === -1) return null;

    posts[index] = this.normalizePost({ ...posts[index], ...updatedFields });
    this.savePosts(posts);

    if (typeof window !== 'undefined') {
      fetch(`${API_BASE_URL}/posts`, {
        method: 'POST',
        headers: AuthService.getAuthHeaders(),
        body: JSON.stringify(posts[index]),
      }).catch((err) => console.warn('Atlas blog update notice:', err));
    }

    return posts[index];
  }

  public static async deletePost(id: string): Promise<boolean> {
    let posts = this.getStoredPosts();
    posts = posts.filter((p) => p.id !== id);
    this.savePosts(posts);

    if (typeof window !== 'undefined') {
      try {
        const res = await fetch(`${API_BASE_URL}/posts/${id}`, {
          method: 'DELETE',
          headers: AuthService.getAuthHeaders(),
        });
        return res.ok;
      } catch (err) {
        console.warn('Atlas blog delete notice:', err);
      }
    }
    return true;
  }
}
